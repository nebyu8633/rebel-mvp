/**
 * Copies the 3D engine from ../lifeos-proto (source of truth) into src/game3d/ and its public
 * assets into public/game3d/. Re-run after changing the prototype:  npm run sync:game3d
 * Only src/game3d/config.ts differs (written here): asset base path, HDRI files, no demo events.
 */
import { cpSync, mkdirSync, readFileSync, rmSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const APP = join(dirname(fileURLToPath(import.meta.url)), "..");
const PROTO = join(APP, "..", "lifeos-proto");
const SRC = join(PROTO, "src");
const DST = join(APP, "src", "game3d");
const PUB = join(APP, "public", "game3d");

// prototype-only entry points / test scene / tests stay out of the app
const SKIP = new Set(["main.tsx", "App.tsx", "vite-env.d.ts", "config.ts", "__tests__", "ui/Hud.tsx", "world/World.tsx", "data/mock.ts"]);

rmSync(DST, { recursive: true, force: true });
cpSync(SRC, DST, {
  recursive: true,
  filter: (p) => {
    const rel = p.slice(SRC.length + 1);
    return !rel || ![...SKIP].some((s) => rel === s || rel.startsWith(s + "/"));
  },
});
writeFileSync(
  join(DST, "config.ts"),
  `/** App-side config for the synced 3D engine (generated by scripts/sync-game3d.mjs). */
export const BASE = "/game3d/";
export const DEV = process.env.NODE_ENV !== "production";
export const HDRI = { day: "/game3d/hdri/esplanade.exr", dusk: "/game3d/hdri/sunset.exr" };
/** No mock events inside the real app. */
export const DEMO_EVENTS = false;
`,
);
writeFileSync(join(DST, "README.md"), "# game3d (generated)\n\nCopied from `lifeos-proto/src` by `npm run sync:game3d`. Do not edit here — edit the prototype and re-sync.\nOnly `config.ts` is app-specific.\n");

// public assets
mkdirSync(PUB, { recursive: true });
for (const d of ["assets/character", "assets/env", "basis"]) cpSync(join(PROTO, "public", d), join(PUB, d), { recursive: true });
mkdirSync(join(PUB, "hdri"), { recursive: true });
for (const n of ["esplanade", "sunset"]) {
  const js = readFileSync(join(PROTO, "node_modules", "@pmndrs", "assets", "hdri", `${n}.exr.js`), "utf8");
  const b64 = js.slice(js.indexOf("base64,") + 7, js.lastIndexOf("'"));
  writeFileSync(join(PUB, "hdri", `${n}.exr`), Buffer.from(b64, "base64"));
}
if (!existsSync(join(PUB, "assets", "character", "character.ktx2.glb"))) throw new Error("character asset missing — run `npm run assets` in lifeos-proto");
console.log("synced game3d →", DST);
